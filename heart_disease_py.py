from scipy.stats import chi2_contingency
import pandas as pd

# ====================== 1. Categorical Columns ======================
cat_features = [
    'Sex_F', 'Sex_M',
    'ChestPainType_ASY', 'ChestPainType_ATA', 'ChestPainType_NAP', 'ChestPainType_TA',
    'RestingECG_LVH', 'RestingECG_Normal', 'RestingECG_ST',
    'ExerciseAngina_N', 'ExerciseAngina_Y',
    'ST_Slope_Down', 'ST_Slope_Flat', 'ST_Slope_Up'
]

# ====================== 2. Chi-Square Test ======================
alpha = 0.05
chi2_results = []

for col in cat_features:
    contingency = pd.crosstab(Df_encode[col], Df_encode['HeartDisease'])
    chi2_stat, p_val, dof, expected = chi2_contingency(contingency)

    decision = 'Reject Null (Keep Feature)' if p_val < alpha else 'Accept Null (Drop Feature)'

    chi2_results.append({
        'Feature': col,
        'Chi2_Statistic': round(chi2_stat, 4),
        'P_Value': round(p_val, 6),
        'Decision': decision
    })

# ====================== 3. Results DataFrame ======================
chi2_df = pd.DataFrame(chi2_results)

# P-Value ke hisaab se sort (important features pehle)
chi2_df = chi2_df.sort_values('P_Value').reset_index(drop=True)

# Display
print(chi2_df)

print("\n--- Features to Keep ---")
print(chi2_df[chi2_df['Decision'] == 'Reject Null (Keep Feature)'])

